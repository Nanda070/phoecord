"""Build docs/DECISIONS.md from the `Ruling:` lines of every plan ledger (docs/<plan>/ai/ledger.md).

Decisions are written only as `Ruling:` lines in a ledger (format: docs/_template/ruling.md);
this file is regenerated from them.

    python scripts/gen_decisions.py          # rewrite docs/DECISIONS.md
    python scripts/gen_decisions.py --check  # exit 1 if it is stale (CI and scripts/check.sh)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
OUT = DOCS / "DECISIONS.md"


def plan_title(plan_dir: Path) -> str:
    readme = plan_dir / "README.md"
    if readme.exists():
        for line in readme.read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                return line[2:].split(":")[0].strip()
    return plan_dir.name


def build() -> str:
    out = [
        "# Decisions",
        "",
        "Every owner decision (`Ruling:` lines from plan ledgers), grouped by plan. Generated by",
        "`python scripts/gen_decisions.py`; never edit by hand: write the decision as a `Ruling:` line",
        "in its plan's `ai/ledger.md` first, then rerun the script.",
    ]
    ledgers = sorted(
        p for p in DOCS.glob("*/ai/ledger.md") if p.parts[-3] != "_template"
    )
    for ledger in ledgers:
        plan_dir = ledger.parent.parent
        rulings = [
            l.strip()
            for l in ledger.read_text(encoding="utf-8").splitlines()
            if l.strip().startswith("Ruling")
        ]
        if not rulings:
            continue
        rel = ledger.relative_to(ROOT).as_posix()
        out += ["", f"## {plan_title(plan_dir)}", "", f"Source: `{rel}`, decisions: {len(rulings)}.", ""]
        out += [f"- {r}" for r in rulings]
    return "\n".join(out) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("docs/DECISIONS.md is stale: run python scripts/gen_decisions.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
